function prettyName(file) {
  return file
    .replace(/\.[^.]+$/, "")
    .replace(/^\d+[_\-]*/, "")
    .replace(/[-_]/g, " ");
}

function renderGallery(el, paths, emptyNote) {
  el.innerHTML = "";
  if (!paths || paths.length === 0) {
    const p = document.createElement("p");
    p.className = "gallery-empty";
    p.textContent = emptyNote || "Ekran görüntüleri yakında eklenecek.";
    el.appendChild(p);
    return;
  }
  for (const src of paths) {
    const name = src.split("/").pop();
    const fig = document.createElement("figure");
    const img = document.createElement("img");
    img.src = src;
    img.alt = prettyName(name);
    img.loading = "lazy";
    img.addEventListener("click", () => openLightbox(src, img.alt));
    const cap = document.createElement("figcaption");
    cap.textContent = prettyName(name);
    fig.append(img, cap);
    el.appendChild(fig);
  }
}

function openLightbox(src, alt) {
  const box = document.getElementById("lightbox");
  const img = box.querySelector("img");
  img.src = src;
  img.alt = alt || "";
  box.hidden = false;
}

function closeLightbox() {
  document.getElementById("lightbox").hidden = true;
}

function boot() {
  const map = {
    "depo-a": MANIFEST["depo-a"],
    "depo-b": MANIFEST["depo-b"],
    "depo-c": MANIFEST["depo-c"],
    depo: [...MANIFEST["depo-a"], ...MANIFEST["depo-b"], ...MANIFEST["depo-c"]],
    ecod: MANIFEST.ecod,
    fatura: MANIFEST.fatura,
    dib: [],
    web: [],
  };

  const emptyNotes = {
    dib: "Bu proje için henüz ekran görüntüsü yok — teknik özet solda.",
    web: "Bu proje için henüz ekran görüntüsü yok — teknik özet solda.",
  };

  document.querySelectorAll("[data-gallery]").forEach((el) => {
    const key = el.getAttribute("data-gallery");
    renderGallery(el, map[key], emptyNotes[key]);
  });

  const depoGallery = document.querySelector("#depo-mobil .gallery");
  document.querySelectorAll("#depo-mobil .tab").forEach((btn) => {
    btn.addEventListener("click", () => {
      document.querySelectorAll("#depo-mobil .tab").forEach((b) => b.classList.remove("active"));
      btn.classList.add("active");
      renderGallery(depoGallery, map[btn.getAttribute("data-tab")]);
    });
  });

  const lb = document.getElementById("lightbox");
  lb.querySelector(".lightbox-close").addEventListener("click", closeLightbox);
  lb.addEventListener("click", (e) => {
    if (e.target === lb) closeLightbox();
  });
  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape") closeLightbox();
  });
}

boot();
