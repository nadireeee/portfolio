const IMG_CACHE_BUST = "20260924hesap";

function prettyName(file) {
  const base = ((file || "").split("?")[0].split("/").pop() || file).trim();
  if (GALLERY_CAPTIONS[file]) return GALLERY_CAPTIONS[file];
  if (GALLERY_CAPTIONS[base]) return GALLERY_CAPTIONS[base];
  const stem = base.replace(/\.thumb\.webp$/i, "").replace(/\.(webp|png|jpe?g)$/i, "");
  for (const [k, v] of Object.entries(GALLERY_CAPTIONS)) {
    if (k.replace(/\.(png|jpe?g)$/i, "") === stem) return v;
  }
  return stem.replace(/^\d+[a-z]?[_\-]*/, "").replace(/[-_]/g, " ");
}

function toFullSrc(src) {
  return src.replace(/\.(png|jpe?g)$/i, ".webp");
}

function toThumbSrc(src) {
  const full = toFullSrc(src);
  return full.replace(/\.webp$/i, ".thumb.webp");
}

function withBust(src) {
  return src.includes("?") ? src : `${src}?v=${IMG_CACHE_BUST}`;
}

let lightboxState = { paths: [], index: 0 };

function setLightboxSrc(img, src) {
  img.onerror = () => {
    // webp yoksa orijinal png/jpg dene
    const fallback = src
      .replace(/\.thumb\.webp(\?|$)/i, ".png$1")
      .replace(/\.webp(\?|$)/i, ".png$1");
    if (fallback !== src) {
      img.onerror = null;
      img.src = fallback;
    }
  };
  img.src = src;
}

function openLightbox(src, alt, paths, index) {
  const box = document.getElementById("lightbox");
  const img = box.querySelector("img");
  lightboxState.paths = paths || [src];
  lightboxState.index = typeof index === "number" ? index : 0;
  const current = lightboxState.paths[lightboxState.index];
  setLightboxSrc(img, current);
  img.alt = alt || prettyName(current);
  box.hidden = false;
  document.body.style.overflow = "hidden";
}

function showLightboxAt(index) {
  const paths = lightboxState.paths;
  if (!paths.length) return;
  const i = (index + paths.length) % paths.length;
  lightboxState.index = i;
  const box = document.getElementById("lightbox");
  const img = box.querySelector("img");
  const src = paths[i];
  setLightboxSrc(img, src);
  img.alt = prettyName(src);
}

function closeLightbox() {
  document.getElementById("lightbox").hidden = true;
  document.body.style.overflow = "";
}

function renderGallery(el, paths, emptyNote) {
  el.innerHTML = "";
  if (!paths || paths.length === 0) {
    const p = document.createElement("p");
    p.className = "gallery-empty";
    p.textContent = emptyNote || "Ekran goruntuleri yakinda eklenecek.";
    el.appendChild(p);
    return;
  }

  // Grid: tiny thumbs (fast). Lightbox: full webp.
  const fullPaths = paths.map((src) => withBust(toFullSrc(src)));
  const thumbPaths = paths.map((src) => withBust(toThumbSrc(src)));

  const frag = document.createDocumentFragment();
  thumbPaths.forEach((thumb, index) => {
    const name = paths[index].split("/").pop();
    const fig = document.createElement("figure");
    const img = document.createElement("img");
    img.src = thumb;
    img.alt = prettyName(name);
    img.loading = "eager";
    img.decoding = "async";
    img.width = 480;
    img.addEventListener("click", () =>
      openLightbox(fullPaths[index], img.alt, fullPaths, index)
    );
    const cap = document.createElement("figcaption");
    cap.textContent = prettyName(name);
    fig.append(img, cap);
    frag.appendChild(fig);
  });
  el.appendChild(frag);
  el.dataset.loaded = "1";
}

function boot() {
  const map = {
    akseker: MANIFEST.akseker,
    cankirli: MANIFEST.cankirli,
    "mobil-sevkiyat": MANIFEST["mobil-sevkiyat"],
    ecod: MANIFEST.ecod,
    fatura: MANIFEST.fatura,
    mikroservisler: MANIFEST.mikroservisler,
    bitirme: MANIFEST.bitirme,
    "maui-dotnet": MANIFEST["maui-dotnet"],
    "staj-cpp": MANIFEST["staj-cpp"],
  };

  // All galleries: tiny thumbs (~2MB total) so everything paints immediately
  document.querySelectorAll("[data-gallery]").forEach((el) => {
    const key = el.getAttribute("data-gallery");
    renderGallery(el, map[key]);
  });

  const depoGallery = document.querySelector("#depo-mobil .gallery");
  document.querySelectorAll("#depo-mobil .tab").forEach((btn) => {
    btn.addEventListener("click", () => {
      document.querySelectorAll("#depo-mobil .tab").forEach((b) => b.classList.remove("active"));
      btn.classList.add("active");
      const key = btn.getAttribute("data-tab");
      depoGallery.dataset.loaded = "0";
      renderGallery(depoGallery, map[key]);
      depoGallery.setAttribute("data-gallery", key);
      depoGallery.classList.add("gallery--phone");
      depoGallery.classList.remove("gallery--desktop");
    });
  });

  const lb = document.getElementById("lightbox");
  lb.querySelector(".lightbox-close").addEventListener("click", closeLightbox);
  lb.addEventListener("click", (e) => {
    if (e.target === lb) closeLightbox();
  });
  document.addEventListener("keydown", (e) => {
    const box = document.getElementById("lightbox");
    if (box.hidden) return;
    if (e.key === "Escape") {
      closeLightbox();
      return;
    }
    if (e.key === "ArrowRight" || e.key === "ArrowDown") {
      e.preventDefault();
      showLightboxAt(lightboxState.index + 1);
    } else if (e.key === "ArrowLeft" || e.key === "ArrowUp") {
      e.preventDefault();
      showLightboxAt(lightboxState.index - 1);
    }
  });
}

boot();
